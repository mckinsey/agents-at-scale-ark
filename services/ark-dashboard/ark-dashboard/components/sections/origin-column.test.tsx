import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, expect, it, vi } from 'vitest';

import { TooltipProvider } from '@/components/ui/tooltip';
import { getAgentOriginLabel } from '@/lib/utils/origin-icon';

import { OriginCell, OriginColumnHeader } from './origin-column';

vi.mock('@/components/namespaced-link', () => ({
  NamespacedLink: (props: React.ComponentProps<'a'>) => <a {...props} />,
}));

describe('OriginColumnHeader', () => {
  it('renders the Origin label and the info trigger', () => {
    render(<OriginColumnHeader tooltip="Where the agent was first created" />);
    expect(screen.getByText('Origin')).toBeInTheDocument();
    expect(screen.getByLabelText('About Origin')).toBeInTheDocument();
  });
});

describe('OriginCell', () => {
  it('renders ARK when origin is missing', () => {
    render(<OriginCell origin={undefined} />);
    expect(screen.getByText('ARK')).toBeInTheDocument();
  });

  it('renders the resolved label for a known origin type', () => {
    render(<OriginCell origin={JSON.stringify({ type: 'github' })} />);
    expect(screen.getByText('GitHub')).toBeInTheDocument();
  });

  it('shows the A2A server name on hover and keeps the row link', async () => {
    render(
      <TooltipProvider>
        <OriginCell
          origin={undefined}
          a2aServerName="simple-agent"
          rowHref="/agents/simple-agent"
        />
      </TooltipProvider>,
    );

    const label = screen.getByText('A2A server');
    expect(label.closest('a')).toHaveAttribute('href', '/agents/simple-agent');

    await userEvent.hover(label);

    expect(
      await screen.findAllByText('A2A server: simple-agent'),
    ).not.toHaveLength(0);
  });
});

describe('getAgentOriginLabel', () => {
  it('labels agents generated by an A2A server', () => {
    expect(
      getAgentOriginLabel({
        'ark.mckinsey.com/a2a-server-name': 'simple-agent',
      }),
    ).toBe('A2A server');
  });

  it('falls back to the origin annotation', () => {
    expect(getAgentOriginLabel({})).toBe('ARK');
  });
});
