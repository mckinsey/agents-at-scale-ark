import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, expect, it, vi } from 'vitest';

import { TooltipProvider } from '@/components/ui/tooltip';

import {
  A2AManagedInfo,
  AgentOriginField,
  AgentStreamingField,
} from './agent-origin-section';

const push = vi.fn();

vi.mock('@/lib/hooks/use-namespaced-navigation', () => ({
  useNamespacedNavigation: () => ({ push }),
}));

describe('A2AManagedInfo', () => {
  it('explains why the agent cannot be edited on hover', async () => {
    render(
      <TooltipProvider>
        <A2AManagedInfo />
      </TooltipProvider>,
    );

    await userEvent.hover(
      screen.getByRole('button', { name: "Why this agent can't be edited" }),
    );

    expect(
      await screen.findAllByText(
        "This agent can't be edited. To change it, update the A2A server.",
      ),
    ).not.toHaveLength(0);
  });
});

describe('AgentOriginField', () => {
  it('opens the A2A server that generated the agent', async () => {
    render(
      <TooltipProvider>
        <AgentOriginField a2aServerName="simple-agent" />
      </TooltipProvider>,
    );

    expect(screen.getByText('A2A server · simple-agent')).toBeInTheDocument();
    await userEvent.click(
      screen.getByRole('button', { name: 'Open A2A server simple-agent' }),
    );

    expect(push).toHaveBeenCalledWith('/a2a/simple-agent');
  });

  it('shows the origin label for agents not generated by an A2A server', () => {
    render(<AgentOriginField origin={undefined} />);

    expect(screen.getByText('ARK')).toBeInTheDocument();
    expect(screen.queryByRole('button')).not.toBeInTheDocument();
  });
});

describe('AgentStreamingField', () => {
  it.each([
    ['true', 'True'],
    ['false', 'False'],
    [undefined, '—'],
  ])('shows %s as %s', (value, label) => {
    render(<AgentStreamingField streamingSupported={value} />);
    const field = screen.getByRole('textbox', { name: 'Streaming' });
    expect(field).toHaveValue(label);
    expect(field).toBeDisabled();
  });
});
